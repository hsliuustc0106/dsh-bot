import type { AgentRuntime } from "@rakazo/adapter-kit";
import type { Prisma, PrismaClient } from "@rakazo/db";

/** Record the selected runtime under the same lease that authorizes execution. */
export async function recordRuntimeIdentity(
  prisma: PrismaClient,
  runtime: AgentRuntime,
  target: { runId: string; botId: string; workerId: string; fence: number },
): Promise<void> {
  const descriptor = runtime.describe({ botId: target.botId });
  const updated = await prisma.run.updateMany({
    where: {
      id: target.runId,
      status: "running",
      leaseOwner: target.workerId,
      leaseFence: target.fence,
    },
    data: { runtimeId: descriptor.id, runtimeVersion: descriptor.adapterVersion },
  });
  if (updated.count !== 1) throw new Error("Run lease lost before runtime start");
  if (
    descriptor.capabilities?.requiresInvocationClaim &&
    !descriptor.capabilities.persistentSessions
  )
    await claimRuntimeInvocation(prisma, target);
}

/** Commit before model startup, independently of callback IDs generated by the model. */
export async function claimRuntimeInvocation(
  prisma: PrismaClient,
  target: { runId: string; botId: string; workerId: string; fence: number },
): Promise<void> {
  await prisma.$transaction((tx) => claimRuntimeInvocationInTransaction(tx, target));
}

export async function claimRuntimeInvocationInTransaction(
  tx: Prisma.TransactionClient,
  target: { runId: string; botId: string; workerId: string; fence: number },
): Promise<void> {
  await tx.$queryRaw`SELECT id FROM runs WHERE id = ${target.runId} FOR UPDATE`;
  const run = await tx.run.findFirst({
    where: {
      id: target.runId,
      botId: target.botId,
      status: "running",
      leaseOwner: target.workerId,
      leaseFence: target.fence,
      leaseExpiresAt: { gt: new Date() },
    },
    select: { spaceId: true, runtimeInputGeneration: true },
  });
  if (!run) throw new Error("Run lease lost before runtime invocation");
  const idempotencyKey = `runtime-invocation:${target.runId}:${run.runtimeInputGeneration}`;
  const previous = await tx.externalEffect.findUnique({ where: { idempotencyKey } });
  if (previous)
    throw new Error(
      "This invocation cannot be replayed safely. Verify unfinished actions before starting a new run.",
    );
  await tx.externalEffect.create({
    data: {
      runId: target.runId,
      spaceId: run.spaceId,
      kind: "runtime_invocation",
      idempotencyKey,
      status: "claimed",
      request: { generation: run.runtimeInputGeneration, fence: target.fence },
    },
  });
}
