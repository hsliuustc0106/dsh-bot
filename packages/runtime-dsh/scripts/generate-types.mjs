import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = await mkdtemp(join(tmpdir(), "dsh-types-"));
try {
  execFileSync(
    process.execPath,
    [
      fileURLToPath(new URL("./bin/tsc", import.meta.resolve("typescript/package.json"))),
      "--ignoreConfig",
      "--strict",
      "--allowJs",
      "--declaration",
      "--emitDeclarationOnly",
      "--skipLibCheck",
      "--module",
      "NodeNext",
      "--moduleResolution",
      "NodeNext",
      "--target",
      "ES2023",
      "--outDir",
      output,
      "src/protocol.mjs",
      "src/frames.mjs",
    ],
    { cwd: root, stdio: "inherit" },
  );
  for (const name of ["protocol", "frames"]) {
    const content = (await readFile(join(output, `${name}.d.mts`), "utf8")).replace(
      "import { z }",
      "import type { z }",
    );
    await writeFile(
      join(root, "src", `${name}.d.mts`),
      `// Generated by scripts/generate-types.mjs; edit the .mjs source.\n${content}`,
    );
  }
} finally {
  await rm(output, { recursive: true, force: true });
}
